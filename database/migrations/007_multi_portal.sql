-- ── Step 1: Extend role CHECK to include Supplier + Manager ────
ALTER TABLE public.profiles
  DROP CONSTRAINT IF EXISTS profiles_role_check;

ALTER TABLE public.profiles
  ADD CONSTRAINT profiles_role_check
  CHECK (role IN (
    'Admin',
    'super_admin',
    'Manager',
    'Customer',
    'Warehouse_Staff',
    'Finance_Officer',
    'Dispatch_Officer',
    'Driver',
    'Supplier'
  ));

-- ── Step 2: Extend profiles with enterprise columns ────────────
ALTER TABLE public.profiles
  ADD COLUMN IF NOT EXISTS employee_number  VARCHAR(50),
  ADD COLUMN IF NOT EXISTS department       VARCHAR(100),
  ADD COLUMN IF NOT EXISTS branch           VARCHAR(100),
  ADD COLUMN IF NOT EXISTS status           VARCHAR(20) DEFAULT 'active'
    CHECK (status IN ('active', 'inactive', 'suspended')),
  ADD COLUMN IF NOT EXISTS last_login       TIMESTAMPTZ,
  ADD COLUMN IF NOT EXISTS phone            VARCHAR(50),
  ADD COLUMN IF NOT EXISTS company_name     VARCHAR(255),
  ADD COLUMN IF NOT EXISTS contact_person   VARCHAR(255),
  ADD COLUMN IF NOT EXISTS tax_number       VARCHAR(100);


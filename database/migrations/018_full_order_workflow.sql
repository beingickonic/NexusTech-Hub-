  WHERE status NOT IN (
    'Pending', 'Awaiting Payment', 'Paid', 'Waiting for Stock', 'Reserved',
    'Picking', 'Packing', 'Ready for Dispatch', 'Assigned', 'Out for Delivery',
    'Delivered', 'Completed', 'Cancelled', 'Refunded', 'Pending Payment Verification',

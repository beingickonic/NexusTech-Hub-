-- 9. Create/Replace reserve_inventory RPC
CREATE OR REPLACE FUNCTION public.reserve_inventory(p_order_id UUID, p_user_id UUID)
RETURNS JSONB AS $$
DECLARE
  v_item RECORD;
  v_inventory RECORD;
  v_available INT;
  v_all_available BOOLEAN := TRUE;
  v_low_stock_items JSONB := '[]'::JSONB;
  v_result JSONB;
BEGIN
  FOR v_item IN
    SELECT oi.product_id, oi.quantity, p.title
    FROM public.order_items oi
    JOIN public.products p ON p.id = oi.product_id
    WHERE oi.order_id = p_order_id
  LOOP
    SELECT i.id, i.quantity_on_hand, i.quantity_reserved, i.reorder_level
    INTO v_inventory
    FROM public.inventory i
    WHERE i.product_id = v_item.product_id
    LIMIT 1;

    IF v_inventory.id IS NULL THEN
      INSERT INTO public.inventory (product_id, quantity_on_hand, quantity_reserved)
      VALUES (v_item.product_id, 0, 0)
      RETURNING id, quantity_on_hand, quantity_reserved, reorder_level INTO v_inventory;
    END IF;

    v_available := COALESCE(v_inventory.quantity_on_hand, 0) - COALESCE(v_inventory.quantity_reserved, 0);

    IF v_available >= v_item.quantity THEN
      UPDATE public.inventory
      SET quantity_reserved = COALESCE(quantity_reserved, 0) + v_item.quantity,
          updated_at = NOW()
      WHERE id = v_inventory.id;
    ELSE
      v_all_available := FALSE;
      v_low_stock_items := v_low_stock_items || jsonb_build_object(
        'product_id', v_item.product_id,
        'title', v_item.title,
        'requested', v_item.quantity,
        'available', GREATEST(0, v_available)
      );
    END IF;
  END LOOP;

  IF v_all_available THEN
    UPDATE public.orders SET status = 'Reserved' WHERE id = p_order_id;
    v_result := jsonb_build_object('success', TRUE, 'status', 'Reserved');
  ELSE
    UPDATE public.orders SET status = 'Waiting for Stock' WHERE id = p_order_id;
    v_result := jsonb_build_object(
      'success', FALSE,
      'status', 'Waiting for Stock',
      'low_stock_items', v_low_stock_items
    );
  END IF;

  RETURN v_result;
END;
$$ LANGUAGE plpgsql SECURITY DEFINER;

-- 10. Create/Replace release_inventory RPC
CREATE OR REPLACE FUNCTION public.release_inventory(p_order_id UUID)
RETURNS JSONB AS $$
DECLARE
  v_item RECORD;
BEGIN
  FOR v_item IN
    SELECT oi.product_id, oi.quantity
    FROM public.order_items oi
    WHERE oi.order_id = p_order_id
  LOOP
    UPDATE public.inventory
    SET quantity_reserved = GREATEST(0, COALESCE(quantity_reserved, 0) - v_item.quantity),
        updated_at = NOW()
    WHERE product_id = v_item.product_id;
  END LOOP;

  RETURN jsonb_build_object('success', TRUE);
END;
$$ LANGUAGE plpgsql SECURITY DEFINER;

-- 11. Create/Replace deduct_inventory RPC (called when picking completed)
CREATE OR REPLACE FUNCTION public.deduct_inventory(p_order_id UUID)
RETURNS JSONB AS $$
DECLARE
  v_item RECORD;
BEGIN
  FOR v_item IN
    SELECT oi.product_id, oi.quantity
    FROM public.order_items oi
    WHERE oi.order_id = p_order_id
  LOOP
    UPDATE public.inventory
    SET quantity_on_hand = GREATEST(0, COALESCE(quantity_on_hand, 0) - v_item.quantity),
        quantity_reserved = GREATEST(0, COALESCE(quantity_reserved, 0) - v_item.quantity),
        updated_at = NOW()
    WHERE product_id = v_item.product_id;

    UPDATE public.products
    SET stock = GREATEST(0, COALESCE(stock, 0) - v_item.quantity)
    WHERE id = v_item.product_id;

    INSERT INTO public.inventory_logs (product_id, order_id, change_amount, reason, notes)
    VALUES (v_item.product_id, p_order_id, -v_item.quantity, 'sale', 'Picking completed');
  END LOOP;

  RETURN jsonb_build_object('success', TRUE);
END;
$$ LANGUAGE plpgsql SECURITY DEFINER;

-- 12. Create auto_create_dispatch function unconditionally (no table refs checked at compile time)
CREATE OR REPLACE FUNCTION public.auto_create_dispatch()
RETURNS TRIGGER
LANGUAGE plpgsql SECURITY DEFINER AS $func$
DECLARE
  v_has_dispatches BOOLEAN;
  v_has_notifications BOOLEAN;
BEGIN
  IF NEW.status = 'Ready for Dispatch' AND (OLD.status IS DISTINCT FROM 'Ready for Dispatch') THEN
    SELECT EXISTS (SELECT 1 FROM information_schema.tables WHERE table_schema = 'public' AND table_name = 'dispatches') INTO v_has_dispatches;
    SELECT EXISTS (SELECT 1 FROM information_schema.tables WHERE table_schema = 'public' AND table_name = 'portal_notifications') INTO v_has_notifications;

    IF v_has_dispatches THEN
      INSERT INTO public.dispatches (order_id, customer_name, customer_phone, delivery_address, delivery_city, status, created_at)
      SELECT NEW.id, COALESCE(NEW.shipping_name, p.full_name), NEW.shipping_phone, NEW.shipping_address, NEW.shipping_city, 'pending', NOW()
      FROM public.profiles p WHERE p.id = NEW.user_id;
    END IF;

    IF v_has_notifications THEN
      INSERT INTO public.portal_notifications (user_id, type, title, message, portal)
      SELECT user_id, 'dispatch', 'Dispatch Created',
        'Order ' || COALESCE(NEW.order_number, '#' || NEW.id) || ' is ready for dispatch.',
        'dispatch'
      FROM public.profiles WHERE role IN ('Admin', 'super_admin', 'Dispatch_Officer', 'Manager');
    END IF;
  END IF;
  RETURN NEW;
END;
$func$;

DROP TRIGGER IF EXISTS trg_auto_create_dispatch ON public.orders;
CREATE TRIGGER trg_auto_create_dispatch
  AFTER UPDATE OF status ON public.orders
  FOR EACH ROW
  WHEN (NEW.status = 'Ready for Dispatch')
  EXECUTE FUNCTION public.auto_create_dispatch();

-- 13. Create sync_order_on_delivery function unconditionally
CREATE OR REPLACE FUNCTION public.sync_order_on_delivery()
RETURNS TRIGGER
LANGUAGE plpgsql SECURITY DEFINER AS $func$
DECLARE
  v_has_orders BOOLEAN;
BEGIN
  IF NEW.status = 'delivered' AND (OLD.status IS DISTINCT FROM 'delivered') THEN
    UPDATE public.orders
    SET status = 'Delivered', payment_status = 'paid'
    WHERE id = NEW.order_id AND status NOT IN ('Delivered', 'Completed', 'Cancelled', 'Refunded');
  END IF;
  RETURN NEW;
END;
$func$;

DO $block$
BEGIN
  IF EXISTS (SELECT 1 FROM information_schema.tables WHERE table_schema = 'public' AND table_name = 'dispatches') THEN
    DROP TRIGGER IF EXISTS trg_sync_order_on_delivery ON public.dispatches;
    CREATE TRIGGER trg_sync_order_on_delivery
      AFTER UPDATE OF status ON public.dispatches
      FOR EACH ROW
      WHEN (NEW.status = 'delivered')
      EXECUTE FUNCTION public.sync_order_on_delivery();
  END IF;
END;
$block$;

-- 14. Create view for active orders workflow (use dynamic SQL for optional tables)
DO $$
BEGIN
  IF EXISTS (SELECT 1 FROM information_schema.tables WHERE table_schema = 'public' AND table_name = 'dispatches')
     AND EXISTS (SELECT 1 FROM information_schema.tables WHERE table_schema = 'public' AND table_name = 'drivers')
     AND EXISTS (SELECT 1 FROM information_schema.tables WHERE table_schema = 'public' AND table_name = 'inventory') THEN
    CREATE OR REPLACE VIEW public.order_workflow_view AS
    SELECT
      o.id, o.order_number, o.status, o.payment_status, o.payment_method, o.priority,
      o.total_amount, o.created_at, o.shipping_name, o.shipping_phone, o.shipping_address,
      o.shipping_city, o.warehouse_id, o.driver_id, o.picked_at, o.packed_at, o.dispatched_at,
      p.id AS customer_id, p.full_name AS customer_name, p.email AS customer_email, p.phone AS customer_phone,
      COALESCE(i.quantity_on_hand, 0) AS stock_available,
      COALESCE(i.quantity_reserved, 0) AS stock_reserved,
      CASE
        WHEN i.quantity_on_hand IS NULL THEN 'no_record'
        WHEN i.quantity_on_hand <= 0 THEN 'out_of_stock'
        WHEN i.quantity_on_hand - COALESCE(i.quantity_reserved, 0) <= 0 THEN 'fully_reserved'
        WHEN i.quantity_on_hand - COALESCE(i.quantity_reserved, 0) < 10 THEN 'low_stock'
        ELSE 'in_stock'
      END AS stock_status,
      d.id AS dispatch_id, d.status AS dispatch_status,
      dr.full_name AS driver_name, dr.phone AS driver_phone
    FROM public.orders o
    LEFT JOIN public.profiles p ON p.id = o.user_id
    LEFT JOIN LATERAL (
      SELECT SUM(COALESCE(i2.quantity_on_hand, 0)) AS quantity_on_hand,
             SUM(COALESCE(i2.quantity_reserved, 0)) AS quantity_reserved
      FROM public.order_items oi2
      LEFT JOIN public.inventory i2 ON i2.product_id = oi2.product_id
      WHERE oi2.order_id = o.id
    ) i ON TRUE
    LEFT JOIN public.dispatches d ON d.order_id = o.id
    LEFT JOIN public.drivers dr ON d.driver_id = dr.id;
  END IF;
END $$;

-- 15. Update process_mpesa_callback to use 'Paid' instead of 'Processing'
CREATE OR REPLACE FUNCTION process_mpesa_callback(
  p_checkout_request_id VARCHAR,
  p_merchant_request_id VARCHAR,
  p_result_code INT,
  p_result_desc TEXT,
  p_amount NUMERIC,
  p_receipt VARCHAR,
  p_phone VARCHAR,
  p_raw_payload JSONB
)
RETURNS JSONB
LANGUAGE plpgsql
SECURITY DEFINER
AS $$
DECLARE
  v_payment RECORD;
  v_order RECORD;
  v_item RECORD;
  v_callback_id UUID;
  v_is_success BOOLEAN;
  v_payment_status VARCHAR;
BEGIN
  v_is_success := (p_result_code = 0);
  v_payment_status := CASE WHEN v_is_success THEN 'paid' ELSE 'failed' END;

  IF EXISTS (SELECT 1 FROM public.payment_callbacks WHERE checkout_request_id = p_checkout_request_id AND processed = true) THEN
    INSERT INTO public.payment_logs (event_type, provider, description, payload)
    VALUES ('duplicate_callback_ignored', 'mpesa', 'Ignored duplicate callback for ' || p_checkout_request_id, p_raw_payload);
    RETURN jsonb_build_object('success', true, 'message', 'Duplicate callback ignored');
  END IF;

  SELECT * INTO v_payment FROM public.payments WHERE transaction_reference = p_checkout_request_id FOR UPDATE;

  IF v_payment IS NULL THEN
    INSERT INTO public.payment_callbacks (checkout_request_id, merchant_request_id, result_code, result_desc, raw_payload, processed)
    VALUES (p_checkout_request_id, p_merchant_request_id, p_result_code, p_result_desc, p_raw_payload, true);
    RETURN jsonb_build_object('success', false, 'error', 'Payment intent not found for reference ' || p_checkout_request_id);
  END IF;

  SELECT * INTO v_order FROM public.orders WHERE id = v_payment.order_id FOR UPDATE;

  INSERT INTO public.payment_callbacks (
    payment_id, checkout_request_id, merchant_request_id, result_code, result_desc, amount, mpesa_receipt, phone_number, raw_payload, processed
  ) VALUES (
    v_payment.id, p_checkout_request_id, p_merchant_request_id, p_result_code, p_result_desc, p_amount, p_receipt, p_phone, p_raw_payload, true
  )
  ON CONFLICT (checkout_request_id) DO UPDATE SET
    merchant_request_id = EXCLUDED.merchant_request_id,
    result_code = EXCLUDED.result_code,
    result_desc = EXCLUDED.result_desc,
    amount = EXCLUDED.amount,
    mpesa_receipt = EXCLUDED.mpesa_receipt,
    phone_number = EXCLUDED.phone_number,
    raw_payload = EXCLUDED.raw_payload,
    processed = true
  RETURNING id INTO v_callback_id;

  UPDATE public.payments SET status = v_payment_status, updated_at = NOW() WHERE id = v_payment.id;

  -- Use 'Paid' instead of 'Processing' to match the new workflow
  UPDATE public.orders 
  SET 
    payment_status = v_payment_status, 
    status = CASE WHEN v_is_success THEN 'Paid' ELSE status END
  WHERE id = v_order.id;

  IF v_is_success THEN
    FOR v_item IN (SELECT product_id, quantity FROM public.order_items WHERE order_id = v_order.id) LOOP
      INSERT INTO public.inventory_logs (product_id, order_id, change_amount, reason, notes)
      VALUES (v_item.product_id, v_order.id, -v_item.quantity, 'sale', 'M-Pesa payment verified');

      UPDATE public.products 
      SET stock = GREATEST(0, stock - v_item.quantity)
      WHERE id = v_item.product_id;
    END LOOP;

    IF v_payment.user_id IS NOT NULL THEN
      INSERT INTO public.notifications (user_id, title, message, type)
      VALUES (v_payment.user_id, 'Payment Received', 'We received your payment of KES ' || p_amount || ' for Order ' || v_order.id || '. Thank you!', 'success');
    END IF;
  END IF;

  RETURN jsonb_build_object('success', true, 'message', 'Callback processed idempotently');
EXCEPTION
  WHEN OTHERS THEN
    INSERT INTO public.payment_logs (event_type, description, payload)
    VALUES ('callback_processing_error', SQLERRM, p_raw_payload);
    RETURN jsonb_build_object('success', false, 'error', SQLERRM);
END;
$$;


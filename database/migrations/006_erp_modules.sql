-- ============================================================
--  Driver status sync trigger
--  When a dispatch is assigned → driver becomes busy
--  When delivered/failed/returned → driver becomes available
-- ============================================================
CREATE OR REPLACE FUNCTION public.sync_driver_status()
RETURNS TRIGGER AS $$
BEGIN
  IF NEW.driver_id IS NOT NULL THEN
    IF NEW.status IN ('assigned', 'picked_up', 'in_transit') THEN
      UPDATE public.drivers SET status = 'busy' WHERE id = NEW.driver_id;
    ELSIF NEW.status IN ('delivered', 'failed', 'returned') THEN
      UPDATE public.drivers SET status = 'available', total_deliveries = total_deliveries + 1
      WHERE id = NEW.driver_id;
    END IF;
  END IF;
  RETURN NEW;
END;
$$ LANGUAGE plpgsql SECURITY DEFINER;

DROP TRIGGER IF EXISTS sync_driver_status_trigger ON public.dispatches;
CREATE TRIGGER sync_driver_status_trigger
  AFTER INSERT OR UPDATE OF status ON public.dispatches
  FOR EACH ROW EXECUTE FUNCTION public.sync_driver_status();

